export function getExposureDurationSec(day: number): number {
  if (day <= 3) return 60; // Дни 1–3: 1 минута
  if (day <= 7) return 90; // Дни 4–7: 1.5 минуты
  if (day <= 10) return 120; // Дни 8–10: 2 минуты
  return 150; // Дни 11–14: 2.5 минуты
}

